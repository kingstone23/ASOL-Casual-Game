  static LegendaryTrickshotModel getById(String id) {
    return trickshots.firstWhere(
      (s) => s.id == id,
      orElse: () => trickshots.first,
    );
  }

  static List<LegendaryTrickshotModel> getFiltered({
    String? master,
    int? difficultyStars,
    String? query,
  }) {
    return trickshots.where((shot) {
      if (master != null && master.isNotEmpty && master != 'all') {
        if (!shot.masterName.toLowerCase().contains(master.toLowerCase())) {
          return false;
        }
      }
      if (difficultyStars != null && difficultyStars > 0) {
        if (shot.difficultyStars != difficultyStars) {
          return false;
        }
      }
      if (query != null && query.trim().isNotEmpty) {
        final q = query.toLowerCase().trim();
        final match = shot.title.toLowerCase().contains(q) ||
            shot.masterName.toLowerCase().contains(q) ||
            shot.masterNickname.toLowerCase().contains(q) ||
            shot.yearAndTournament.toLowerCase().contains(q) ||
            shot.description.toLowerCase().contains(q);
        if (!match) return false;
      }
      return true;
    }).toList();
  }
